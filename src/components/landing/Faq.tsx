const FaqItem = ({ q, a }: { q: string; a: string }) => {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);
  return (
    <div className={`faq-item${open ? ' open' : ''}`}>
      <button className="faq-q" onClick={() => setOpen((o) => !o)}>
        {q}<span className="ic">+</span>
      </button>
      <div className="faq-a" ref={ref} style={{ maxHeight: open ? ref.current?.scrollHeight ?? 400 : 0 }}>
        <p>{a}</p>
      </div>
    </div>
  );
};

const Faq = () => {
  const [all, setAll] = useState(false);
  return (
    <section className="sec" id="faq" style={{ background: 'var(--deep)' }}>
      <div className="wrap">
        <Reveal className="eyebrow">// 14 · ВОПРОСЫ</Reveal>
        <Reveal as="h2" className="sec-title grad-text">Частые вопросы об обучении нейросетям</Reveal>
        <Reveal className="faq">
          {QA.map((x, i) => (
            <div key={x.q} className={!all && i >= 10 ? 'faq-hidden' : undefined}>
              <FaqItem {...x} />
            </div>
          ))}
        </Reveal>
        {!all && (
          <Reveal className="faq-more">
            <button type="button" className="btn btn-ghost" onClick={() => setAll(true)}>
              Показать все {QA.length} вопросов
            </button>
          </Reveal>
        )}
      </div>
    </section>
  );
};

export default Faq;